#pragma once

/** @class InteractiveCodedUnit
 *  @brief class InteractiveCodedUnit
 *
 *  Conveys the encoded blocks inside the bitstream.
 */

#include "video_layer/icov_stream.h"

namespace icov {
namespace bitstream {

class InteractiveCodedUnit {
public:
  InteractiveCodedUnit(const byte *encodedData, int8b dataLength)
      : m_encodedData(encodedData), m_dataLength(dataLength) {}

  const int8b GetDataLength() const { return m_dataLength; }

  const byte *GetEncodedData() const { return m_encodedData; }

private:
  const byte *m_encodedData;
  int8b m_dataLength;
};
} // namespace bitstream
} // namespace icov
